package com.bitnic.bitnicorm;

/**
 * Точка расширения для шифрования сериализованных BLOB-полей.
 *
 * <p>Подключается приложением через {@link Configure#setBlobCrypto(IBlobCrypto)}. Если не задан,
 * ORM работает как раньше (без шифрования). Реализация сама решает, помечать ли данные
 * (например, магическим префиксом), чтобы {@link #decrypt(byte[])} мог отличить
 * зашифрованные значения от старых незашифрованных.</p>
 */
public interface IBlobCrypto {

    /**
     * Шифрует сериализованные байты перед записью в БД.
     *
     * @param plain исходные байты
     * @return зашифрованные байты, либо {@code null}, если шифрование не выполнено (записывается как есть)
     */
    byte[] encrypt(byte[] plain);

    /**
     * Расшифровывает байты, прочитанные из БД.
     *
     * @param data байты из БД (могут быть как зашифрованными, так и старыми незашифрованными)
     * @return расшифрованные байты, либо исходные байты для старых записей,
     *         либо {@code null}, если расшифровать не удалось
     */
    byte[] decrypt(byte[] data);
}
